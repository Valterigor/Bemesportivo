const { test, expect } = require('@playwright/test');
for (const width of [390, 1280]) {
  test('vitrine e cadastro de interesse em ' + width + 'px', async ({ page }) => {
    await page.setViewportSize({ width, height: 850 });
    await page.goto('/loja');
    await page.getByRole('button', { name: 'Recusar opcionais' }).click();
    await expect(page.locator('.store-product')).toHaveCount(6);
    await expect(page.getByText('A próxima coleção começa com a sua escolha.')).toBeVisible();
    await expect(page.getByRole('button', { name: 'Revisar pedido' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Salvar lista e receber aviso' })).toBeDisabled();
    await page.getByLabel('Tamanho de Camiseta BE preta', { exact: true }).selectOption('M');
    await page.getByRole('button', { name: 'Adicionar aos desejos', exact: true }).first().click();
    await page.getByLabel('Tamanho de Short BE preto', { exact: true }).selectOption('G');
    await page.locator('.store-product').nth(1).getByRole('button').click();
    await expect(page.locator('#store-wishlist-count')).toHaveText('2');
    await page.reload();
    await expect(page.locator('#store-wishlist-count')).toHaveText('2');
    await expect(page.locator('#store-wishlist-total')).toContainText('119,80');
    await page.getByRole('button', { name: 'Remover Short BE preto', exact: true }).click();
    await expect(page.locator('#store-wishlist-count')).toHaveText('1');
    await expect(page.locator('#store-wishlist-total')).toContainText('59,90');
    await page.getByLabel('Seu nome').fill('Teste local');
    await page.getByLabel('WhatsApp com DDD').fill('11999990000');
    await page.getByRole('checkbox').check();
    const submitted = page.waitForRequest(r => r.url().endsWith('/api/store-interest') && r.method() === 'POST');
    await page.getByRole('button', { name: 'Salvar lista e receber aviso' }).click();
    expect((await submitted).postDataJSON().items).toEqual([{ productId: 'camiseta-be', size: 'M' }]);
    await expect(page.locator('#store-form-status')).toContainText('Teste local registrado');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.route('**/api/store-interest', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{}' }));
    await page.getByLabel('Seu nome').fill('Teste local');
    await page.getByLabel('WhatsApp com DDD').fill('11999990000');
    await page.getByRole('checkbox').check();
    await page.getByRole('button', { name: 'Salvar lista e receber aviso' }).click();
    await expect(page.locator('#store-form-status')).toContainText('Não conseguimos confirmar');
    await expect(page.locator('#store-wishlist-count')).toHaveText('1');
    const stored = await page.evaluate(() => localStorage.getItem('beStoreWishlistV1'));
    expect(stored).not.toContain('11999990000');
    expect(stored).not.toContain('Teste local');
  });
}
