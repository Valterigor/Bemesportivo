'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'be-version-test-'));
const remote = path.join(temp, 'remote.git');
const repo = path.join(temp, 'site');
const script = path.resolve(__dirname, '../../scripts/site-version.cjs');
const git = (args, cwd = repo) => execFileSync('git', args, {cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']}).trim();
fs.mkdirSync(repo);
git(['init', '--bare', remote], temp);
git(['init', '-b', 'main']);
git(['config', 'user.name', 'Version Test']);
git(['config', 'user.email', 'test@example.invalid']);
git(['remote', 'add', 'origin', remote]);
fs.writeFileSync(path.join(repo, 'index.html'), 'old');
git(['add', '.']); git(['commit', '-m', 'old']);
git(['tag', 'site-old']);
fs.writeFileSync(path.join(repo, 'index.html'), 'new');
fs.writeFileSync(path.join(repo, 'new.txt'), 'new file');
git(['add', '.']); git(['commit', '-m', 'new']);
git(['push', 'origin', 'main', '--tags']);
const before = git(['rev-parse', 'HEAD']);
fs.writeFileSync(path.join(repo, 'index.html'), 'local unfinished work');
const run = args => spawnSync(process.execPath, [script, ...args], {cwd: repo, encoding: 'utf8'});
assert.equal(run(['prepare', '--all']).status, 1);
assert.equal(run(['prepare', 'site-missing']).status, 1);
const result = run(['prepare', 'site-old']);
assert.equal(result.status, 0, result.stderr);
const branch = result.stdout.match(/Branch: (rollback\/\S+)/)[1];
assert.equal(git(['rev-parse', `${branch}^{tree}`]), git(['rev-parse', 'site-old^{tree}']));
assert.equal(git(['rev-parse', `${branch}^`]), before);
assert.equal(git(['rev-parse', 'HEAD']), before);
assert.equal(fs.readFileSync(path.join(repo, 'index.html'), 'utf8'), 'local unfinished work');
assert.equal(git(['rev-parse', 'main'], remote), before);
assert.match(git(['tag', '--list', 'site-before-rollback-*']), /^site-before-rollback-/);
console.log('PASS: exact rollback tree, history preserved, dirty workspace untouched, no remote mutation, invalid versions rejected.');
